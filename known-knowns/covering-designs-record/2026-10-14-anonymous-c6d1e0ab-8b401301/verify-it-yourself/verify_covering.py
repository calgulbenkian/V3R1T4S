#!/usr/bin/env python3
"""
Standalone exact verifier for Covering Designs C(v, k, t) (m = t) and
Lottery Designs L(v, k, t, m) (m > t).

Given a JSON or text file describing parameters (v, k, t, m) and blocks:
1. Checks parameter ranges: 1 <= t <= m <= v <= 99, t <= k <= 25, t <= 8.
2. Checks every block has exactly k distinct integers in {1, ..., v}, and all
   blocks are distinct.
3. For plain coverings (m == t), recursively computes the exact Schonheim lower
   bound L(v, k, t) and asserts b >= L(v, k, t).
4. Exhaustively enumerates all C(v, m) m-subsets of {1, ..., v} (asserting
   C(v, m) <= 5e9) using 64-bit integer bitmasks and verifies that every
   m-subset intersects at least one block in >= t points.
"""
import itertools
import json
import math
import os
import sys


def schonheim_bound(v: int, k: int, t: int) -> int:
    if t == 0:
        return 1
    return math.ceil((v / k) * schonheim_bound(v - 1, k - 1, t - 1))


def load_design(path: str):
    raw = open(path, "r", encoding="utf-8").read().strip()
    if raw.startswith("{"):
        d = json.loads(raw)
        v = int(d["v"])
        k = int(d["k"])
        t = int(d["t"])
        m = int(d.get("m", t))
        blocks = [[int(x) for x in blk] for blk in d["blocks"]]
        return v, k, t, m, blocks
    else:
        lines = [l.strip() for l in raw.splitlines() if l.strip() and not l.strip().startswith("#")]
        header = [int(x) for x in lines[0].replace(",", " ").split()]
        if len(header) == 3:
            v, k, t = header
            m = t
        elif len(header) == 4:
            v, k, t, m = header
        else:
            raise ValueError("Text header must be 'v k t' or 'v k t m'")
        blocks = [[int(x) for x in l.replace(",", " ").split()] for l in lines[1:]]
        return v, k, t, m, blocks


def verify_design(v: int, k: int, t: int, m: int, blocks):
    if not (1 <= t <= m <= v <= 99 and t <= k <= 25 and t <= 8):
        return False, f"FAIL: parameters out of range (v={v}, k={k}, t={t}, m={m})"
    b = len(blocks)
    if b == 0:
        return False, "FAIL: empty block list"

    block_masks = []
    seen = set()
    for idx, blk in enumerate(blocks):
        if len(blk) != k:
            return False, f"FAIL: block {idx} has length {len(blk)} != k={k}"
        s = set(blk)
        if len(s) != k:
            return False, f"FAIL: block {idx} has duplicate points: {blk}"
        if any(x < 1 or x > v for x in s):
            return False, f"FAIL: block {idx} has point outside 1..{v}: {blk}"
        mask = 0
        for x in s:
            mask |= (1 << (x - 1))
        if mask in seen:
            return False, f"FAIL: duplicate block at index {idx}: {sorted(s)}"
        seen.add(mask)
        block_masks.append(mask)

    if m == t:
        sch = schonheim_bound(v, k, t)
        if b < sch:
            return False, f"FAIL: b={b} is below Schonheim bound L({v},{k},{t})={sch}"
    else:
        sch = 1

    total_m_subsets = math.comb(v, m)
    if total_m_subsets > 5_000_000_000:
        return False, f"FAIL: C({v},{m})={total_m_subsets} > 5e9"

    if m == t:
        # Plain covering: every t-subset is a subset of at least one k-block.
        # Enumerate all t-subsets generated by the b blocks and count distinct t-subsets!
        covered = set()
        for blk in blocks:
            s_blk = tuple(sorted(blk))
            for comb in itertools.combinations(s_blk, t):
                covered.add(comb)
        if len(covered) != total_m_subsets:
            missing = total_m_subsets - len(covered)
            return False, f"FAIL: plain covering C({v},{k},{t}) with b={b} leaves {missing}/{total_m_subsets} {t}-subsets uncovered"
        return True, f"PASS kind=plain params=C({v},{k},{t}) blocks={b} schonheim={sch} covered={len(covered)}/{total_m_subsets}"
    else:
        # Lottery covering (m > t): every m-subset meets at least one block in >= t points.
        # Generate all m-subsets covered by the b blocks:
        # An m-subset of {0..v-1} meets block B in >= t points iff it contains at least one
        # t-subset of B extended by any (m-t)-subset of {0..v-1}.
        # Even simpler and purely independent: check all C(v, m) m-subsets directly or via
        # covered set if C(v, m) <= 5,000,000.
        covered_masks = set()
        all_pts = list(range(v))
        for blk in blocks:
            b_zero = [x - 1 for x in sorted(blk)]
            b_set = set(b_zero)
            rem_pts = [x for x in all_pts if x not in b_set]
            for r in range(t, min(k, m) + 1):
                if m - r > len(rem_pts):
                    continue
                in_masks = []
                for c_in in itertools.combinations(b_zero, r):
                    im = 0
                    for x in c_in:
                        im |= (1 << x)
                    in_masks.append(im)
                for c_out in itertools.combinations(rem_pts, m - r):
                    om = 0
                    for x in c_out:
                        om |= (1 << x)
                    for im in in_masks:
                        covered_masks.add(im | om)
        if len(covered_masks) != total_m_subsets:
            missing = total_m_subsets - len(covered_masks)
            return False, f"FAIL: lottery covering L({v},{k},{t},{m}) with b={b} leaves {missing}/{total_m_subsets} {m}-subsets uncovered"
        return True, f"PASS kind=lottery params=L({v},{k},{t},{m}) blocks={b} covered={len(covered_masks)}/{total_m_subsets}"


def self_test():
    # 1. Fano plane C(7, 3, 2) = 7
    fano = [[1,2,3],[1,4,5],[1,6,7],[2,4,6],[2,5,7],[3,4,7],[3,5,6]]
    ok, msg = verify_design(7, 3, 2, 2, fano)
    if not ok:
        print("SELF-TEST FAIL on valid Fano plane:", msg)
        sys.exit(1)
    ok_bad, msg_bad = verify_design(7, 3, 2, 2, fano[:-1])
    if ok_bad:
        print("SELF-TEST FAIL: accepted incomplete Fano plane!")
        sys.exit(1)
    # 2. Lottery design L(7, 6, 3, 4) = 1
    ok_l, msg_l = verify_design(7, 6, 3, 4, [[1,2,3,4,5,6]])
    if not ok_l:
        print("SELF-TEST FAIL on valid L(7,6,3,4):", msg_l)
        sys.exit(1)
    ok_lbad, msg_lbad = verify_design(8, 6, 3, 4, [[1,2,3,4,5,6]])
    if ok_lbad:
        print("SELF-TEST FAIL: accepted invalid L(8,6,3,4) with 1 block!")
        sys.exit(1)
    print("SELF-TEST PASS:", msg, "|", msg_l, "| rejected controls:", msg_bad, "|", msg_lbad)


if __name__ == "__main__":
    if len(sys.argv) < 2 or sys.argv[1] == "--self-test":
        self_test()
        sys.exit(0)
    for arg in sys.argv[1:]:
        v, k, t, m, blocks = load_design(arg)
        ok, msg = verify_design(v, k, t, m, blocks)
        print(f"file={os.path.basename(arg)} {msg}")
        if not ok:
            sys.exit(1)
